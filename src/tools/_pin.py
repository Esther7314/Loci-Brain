"""
========================================
tools/_pin.py — pin 的闸（二改 D 件，2026-08-16）
========================================

`pin` 不砍，**语义收窄**：

    从「这条重要」  →  「这条是我要怎么做」

配闸的做法照 `tools/_rooms.py` 房间填错当场拒的样子：**当场拒 + 说清要求 + 举个改写例**。

------------------------------------------------------------
为什么收窄这一下值得单开一个文件
------------------------------------------------------------
✅ 收窄之后，全局 CLAUDE.md 里那条人肉警告**直接消失**：
   「反复出现的缺点不能直接钉，会变成『我要犯这个错』」
   —— 缺点根本钉不上去了，**因为它不是祈使句**。

📌 她 8-16 长出来的通用判据（比这个功能本身值钱）：
   **一条规矩需要一句人肉警告去防误用，说明那个盒子装错了东西。**
   看见人肉警告，正确反应不是把它写得更醒目，是去问**它在替哪个设计缺陷值班**。

📌 为什么门口那张纸只留准则（时机判据）：准则管的是**我怎么行动**，
   而行动发生在检索之前 —— 开口之前来不及去搜的，才留在门口。
   一条描述性的「我是个急性子」放在门口只会变成判词；
   一条「我要先跑基线再动代码」放在门口，是真的会改变下一步动作。

⚠️ 词表是**初版，我拍的**（她 8-16：「闸的词表我先定着用」），
   等第 10 节工具描述英文化那一步一起过。她看到不对味有权改。
⚠️ 已经钉住的存量**不动**——这一闸只管新钉的。

对外暴露：check_pin_imperative(content) → str | None（None=放行）
========================================
"""

import re

# 正文前多少字之内要出现祈使的形状。
# 为什么是「前 N 字」而不是全文：一条准则的祈使句一定在开头——
# 「我要怎么做」写在第三段的，那是一条认知顺带提了一句该怎么办，不是准则。
_HEAD_CHARS = 60

# 初版词表（我拍的）。每一条对应一种真的会出现在准则里的说法：
#   我要 / 我不  —— 最直接的朝向
#   先…再       —— 顺序型（「先跑基线再动代码」）
#   别(?!人)    —— 禁止型；(?!人) 挡掉「别人」这个高频误命中
#   必须 / 就说 / 就停 —— 硬约束
#   每次        —— 触发型（「每次她说累就停下」）
#   发现…立即   —— 条件触发型
_IMPERATIVE_RE = re.compile(
    r"我要|我不|先.*再|别(?!人)|必须|就说|就停|每次|发现.*立即"
)


def looks_imperative(content: str) -> bool:
    """正文前 60 字里有没有「我要怎么做」的形状。"""
    return bool(_IMPERATIVE_RE.search(str(content or "")[:_HEAD_CHARS]))


def check_pin_imperative(content: str) -> str | None:
    """pin 的闸。放行返回 None，拦住返回给调用方看的拒绝文案。

    拒绝文案照 _rooms.py 的样子：说清**要求**、说清**为什么**、**举一个改写例**。
    只报「不合法」而不给出路的错误，会让人把它当噪音绕过去。
    """
    if looks_imperative(content):
        return None
    head = str(content or "").strip().replace("\n", " ")[:40]
    return (
        "pin 拒绝：钉着的东西是**准则**，不是「这条重要」。\n"
        "准则的形状是「我要怎么做」——一句我下次真的会照着做的话，"
        f"而这条读起来是在**描述**：「{head}…」\n"
        "怎么改：把描述翻成朝向。\n"
        "  ✗ 描述：我总是在验收的时候心急。\n"
        "  ✓ 朝向：我要先跑一遍基线再动代码。\n"
        "📌 翻不出来就**别钉**，让它留在认知里——"
        "把缺点钉成准则，语义就成了「我要犯这个错」。\n"
        "（认得的说法：我要 / 我不 / 先…再 / 别… / 必须 / 每次… / 发现…立即）"
    )
